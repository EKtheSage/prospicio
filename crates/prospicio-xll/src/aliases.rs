//! The names functions had before they were grouped (`docs/design/xll.md`,
//! decision 47): each old name stays registered for one release, hidden from
//! the Insert Function dialog, so a workbook saved with it still calculates.
//! Kept through 0.0.9 and removed in 0.0.10.

/// An old name, still exported and registered, that runs the function now
/// exported as `target`.
#[derive(Debug)]
pub struct Alias {
    pub symbol: &'static str,
    pub name: &'static str,
    pub target: &'static str,
}

impl Alias {
    const fn new(symbol: &'static str, name: &'static str, target: &'static str) -> Self {
        Self {
            symbol,
            name,
            target,
        }
    }
}

