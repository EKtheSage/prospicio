"""Regenerate validation/reference/reserving_exhibits_python.csv.

Uses chainladder-python's VotingChainladder, which weights several methods'
ultimates by origin. Run from the repository root:

    uv run --no-project --with chainladder==0.10.1 python validation/scripts/reserving_exhibits_python.py

The triangle is validation/data/genins_premium.csv (GenIns paid with the
premium of R ChainLadder's Clark example); the exposure is the premium's
latest diagonal, as in reserving_expected_loss_python.py. The voting
estimators are the chain ladder, Bornhuetter-Ferguson at an apriori of 0.75
and Cape Cod, each on the volume-weighted development with no tail.

`method` names the weighting case; `quantity` is a component's
`ultimate:<name>`, the voting `ultimate` or `reserve` (ultimate less the
latest paid) per origin, or their totals; `arg` is the origin year. Every
case's weights sum to 1 in each origin: VotingChainladder divides by their
sum and prospicio refuses weights that do not sum to 1.
"""

import csv
import math
import warnings

import chainladder as cl
import numpy as np
import pandas as pd

OUT = "validation/reference/reserving_exhibits_python.csv"
VER = cl.__version__
REL = 1e-9
ESTIMATORS = [
    ("cl", lambda: cl.Chainladder()),
    ("bf", lambda: cl.BornhuetterFerguson(apriori=0.75)),
    ("cc", lambda: cl.CapeCod()),
]
# (case, weights per origin as rows of (cl, bf, cc)); 10 origins.
CASES = [
    (
        "phased",
        [[1.0, 0.0, 0.0]] * 4 + [[0.5, 0.5, 0.0]] * 3 + [[0.0, 0.5, 0.5]] * 2 + [[0.0, 0.0, 1.0]],
    ),
    ("blend", [[0.5, 0.25, 0.25]] * 10),
    ("single_bf", [[0.0, 1.0, 0.0]] * 10),
]


def read_triangle(name):
    df = pd.read_csv(f"validation/data/{name}.csv", comment="#")
    df["origin"] = df["origin"].astype(str)
    df["valuation"] = (df["origin"].astype(int) + df["development"] // 12 - 1).astype(str)
    return cl.Triangle(
        df,
        origin="origin",
        development="valuation",
        columns=["paid", "premium"],
        cumulative=True,
    )


def fmt(x):
    return repr(float(x))


def main():
    rows = []

    def emit(case, quantity, arg, value, source):
        value = float(value)
        if math.isnan(value):
            raise ValueError(f"NaN for {case} {quantity} {arg}")
        rows.append(["genins_premium", case, quantity, arg, fmt(value), 0, REL, source])

    tri = read_triangle("genins_premium")
    paid = cl.Development(average="volume").fit_transform(tri["paid"])
    exposure = tri["premium"].latest_diagonal
    origins = [str(d.year) for d in paid.origin.to_timestamp()]
    latest = paid.latest_diagonal.values[0, 0, :, 0]
    names = [n for n, _ in ESTIMATORS]

    for case, weights in CASES:
        estimators = [(n, make()) for n, make in ESTIMATORS]
        vot = cl.VotingChainladder(estimators=estimators, weights=np.array(weights))
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            vot.fit(paid, sample_weight=exposure)
        src = (
            f"chainladder-python {VER}: VotingChainladder(estimators=[('cl', Chainladder()), "
            "('bf', BornhuetterFerguson(apriori=0.75)), ('cc', CapeCod())], "
            f"weights={weights!r}).fit(Development(average='volume').fit_transform(paid), "
            "sample_weight=premium.latest_diagonal)"
        )
        for n in names:
            ult = vot.named_estimators_[n].ultimate_.values[0, 0, :, 0]
            for i, o in enumerate(origins):
                emit(case, f"ultimate:{n}", o, ult[i], src + f".named_estimators_['{n}'].ultimate_")
        ult = vot.ultimate_.values[0, 0, :, 0]
        for i, o in enumerate(origins):
            emit(case, "ultimate", o, ult[i], src + ".ultimate_")
            emit(case, "reserve", o, ult[i] - latest[i], src + ".ibnr_")
        emit(case, "total_ultimate", "", ult.sum(), src + ".ultimate_.sum()")
        emit(case, "total_reserve", "", (ult - latest).sum(), src + ".ibnr_.sum()")

    with open(OUT, "w", newline="") as f:
        f.write(f"# Generated by validation/scripts/reserving_exhibits_python.py with chainladder-python {VER}.\n")
        f.write("# VotingChainladder on validation/data/genins_premium.csv: column paid, exposure the latest\n")
        f.write("# diagonal of premium, no tail. reserve is ultimate minus the latest paid (ibnr_).\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["dataset", "method", "quantity", "arg", "expected", "abs_tol", "rel_tol", "source"])
        w.writerows(rows)
    print(f"wrote {len(rows)} cases to {OUT}")


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
