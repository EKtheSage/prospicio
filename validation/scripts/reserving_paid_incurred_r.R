rows <- character(0)
emit <- function(dataset, quantity, arg, value, source) {
  rows <<- c(rows, sprintf("%s,%s,%s,%s,%s,%s,%s", dataset, quantity, arg,
                           sprintf("%.17g", value), format(ABS), format(REL), source))
}

for (case in list(list("usaa", USAApaid, USAAincurred), list("dahms", dahms_p, dahms_i))) {
  name <- case[[1]]
  e <- new.env(parent = asNamespace("ChainLadder"))
  e$triangleP <- case[[2]]
  e$triangleI <- case[[3]]
  for (x in as.list(body(PaidIncurredChain))[-1]) eval(x, e)
  out <- PaidIncurredChain(case[[2]], case[[3]])
  stopifnot(isTRUE(all.equal(out$Res.Tot, e$PIC.RisTot, tolerance = 0)))
  J <- ncol(e$triangleP)
  src <- sprintf("R ChainLadder %s: PaidIncurredChain", VER)
  for (j in 1:J) emit(name, "sigma", j - 1, sqrt(e$sigma2.hat[j]), paste0(src, " sqrt(sigma2.hat)"))
  for (j in 1:(J - 1)) emit(name, "tau", j - 1, sqrt(e$tau2.hat[j]), paste0(src, " sqrt(tau2.hat)"))
  for (j in 1:(J - 1)) emit(name, "beta", j - 1, e$beta[j], paste0(src, " beta"))
  sd <- sqrt(diag(e$Ainv))
  for (j in 1:J) {
    emit(name, "phi", j - 1, e$theta.post[j], paste0(src, " theta.post (Phi)"))
    emit(name, "phi_sd", j - 1, sd[j], paste0(src, " sqrt(diag(solve(A))) (Phi)"))
  }
  for (j in 1:(J - 1)) {
    emit(name, "psi", j - 1, e$theta.post[J + j], paste0(src, " theta.post (Psi)"))
    emit(name, "psi_sd", j - 1, sd[J + j], paste0(src, " sqrt(diag(solve(A))) (Psi)"))
  }
  for (i in 2:J) {
    year <- FIRST + i - 1L
    msep_i <- (exp((1 - e$beta[J + 1 - i]) * (e$v2[J] - e$w2[J + 1 - i]) +
                   e$E[i - 1, ] %*% e$Ainv %*% e$E[i - 1, ]) - 1) * e$PIC.Ult[i - 1]^2
    emit(name, "ultimate", year, out$Ult.Loss.Origin[i - 1], paste0(src, "$Ult.Loss.Origin"))
    emit(name, "reserve", year, out$Res.Origin[i - 1], paste0(src, "$Res.Origin"))
    emit(name, "std_err", year, sqrt(msep_i), paste0(src, " the i == k term of the msep sum, square root"))
  }
  emit(name, "ultimate_after_first", "", out$Ult.Loss, paste0(src, "$Ult.Loss (origins after the first)"))
  emit(name, "total_reserve", "", out$Res.Tot, paste0(src, "$Res.Tot"))
  emit(name, "total_std_err", "", out$s.e., paste0(src, "$s.e."))
}

header <- c(
