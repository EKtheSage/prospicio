from_rows <- function(rows) {
  n <- length(rows)
  m <- matrix(NA_real_, n, n, dimnames = list(origin = 0:(n - 1), dev = 1:n))
  for (i in seq_len(n)) m[i, seq_along(rows[[i]])] <- rows[[i]]
  as.triangle(m)
}

write_data <- function(paid, incurred, path, header) {
  n <- nrow(paid)
  lines <- c(header, "origin,development,paid,incurred")
  for (i in 1:n) for (j in 1:n) if (!is.na(paid[i, j])) {
    lines <- c(lines, sprintf("%d,%d,%.17g,%.17g", FIRST + i - 1L, 12L * j,
                              paid[i, j], incurred[i, j]))
  }
  writeLines(lines, path)
}

