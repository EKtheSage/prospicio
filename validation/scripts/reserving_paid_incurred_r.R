# Regenerate validation/data/usaa.csv, validation/data/dahms.csv and
# validation/reference/reserving_paid_incurred_r.csv from R ChainLadder's
# PaidIncurredChain (Merz and Wuthrich 2010, the paid-incurred chain with
# non-informative priors).
#
# Run from the repository root:
#
#     Rscript validation/scripts/reserving_paid_incurred_r.R
#
# Datasets: R ChainLadder's USAApaid and USAAincurred (origins 0..9
# relabelled 2001..2010, development 1..10 as 12..120 months), and the
# paid and incurred triangles of Dahms (2008) as printed in Merz and
# Wuthrich, "Estimation of tail development factors in the paid-incurred
# chain reserving method" (Variance 7(1), 2013; preprint of 2010-11-22),
# Tables 1 and 2, the data of Merz and Wuthrich (2010)'s example (origins
# 0..9 relabelled 2001..2010).
#
# R returns only the totals and the origins after the first. The script
# evaluates the function's body statement by statement in an environment
# whose parent is the package namespace, so that the intermediates
# (sigma2.hat, tau2.hat, beta, theta.post, Ainv, the per-origin terms of
# the msep sum) are written too. `arg` is the 0-based development period j
# of a per-period quantity, the origin year of a per-origin one, and empty
# for totals.

