# Regenerate validation/reference/reserving_glm_r.csv: the over-dispersed
# Poisson reserving model as R's quasi-Poisson GLM,
#
#     glm(inc ~ factor(origin) + factor(dev), family = quasipoisson)
#
# fitted to the observed incremental cells (method `odp_glm`), and the same
# cross-classified model with a gamma error (`odp_glm_gamma`,
# `family = Gamma(link = "log")`) and a Tweedie error of power 1.5
# (`odp_glm_tweedie`, statmod's `tweedie(var.power = 1.5, link.power = 0)`).
# Every fit's dispersion is Pearson's, as summary.glm reports it.
#
# Needs the statmod package. Run from the repository root:
#
#     Rscript validation/scripts/reserving_glm_r.R
#
# Triangles are read from validation/data/*.csv. RAA is left out: it has a
# negative increment (1982 at 84 months), which R's quasipoisson family
# rejects ("negative values not allowed"), as does prospicio-glm's Poisson family.
#
# Quantities: `coefficient` and `std_error` (arg is the prospicio-models column
# name, e.g. "origin[2002]" for R's "factor(origin)2002"), `dispersion`
# (Pearson, as summary.glm reports it), `reserve` (arg is the origin year;
# the sum of predicted future cells) and `total_reserve`.

OUT <- "validation/reference/reserving_glm_r.csv"
DATASETS <- c("genins", "abc")
REL <- 1e-9

FAMILIES <- list(
  odp_glm = list(family = quasipoisson(), label = "quasipoisson"),
  odp_glm_gamma = list(family = Gamma(link = "log"), label = "Gamma(link = 'log')"),
  odp_glm_tweedie = list(family = statmod::tweedie(var.power = 1.5, link.power = 0),
                         label = "statmod::tweedie(var.power = 1.5, link.power = 0)")
)

rows <- character(0)
emit <- function(dataset, method, quantity, arg, value, source) {
  rows <<- c(rows, sprintf("%s,%s,%s,%s,%s,0,%s,%s", dataset, method, quantity, arg,
                           sprintf("%.17g", value), format(REL), source))
}

rename <- function(name) {
  name <- sub("^factor\\(origin\\)(.*)$", "origin[\\1]", name)
  sub("^factor\\(dev\\)(.*)$", "development[\\1]", name)
}

for (name in DATASETS) {
  d <- read.csv(file.path("validation/data", paste0(name, ".csv")), comment.char = "#")
  d <- d[order(d$origin, d$development), ]
  d$inc <- ave(d$value, d$origin, FUN = function(v) c(v[1], diff(v)))
  d$dev <- d$development
  origins <- sort(unique(d$origin))
  devs <- sort(unique(d$dev))

  for (method in names(FAMILIES)) {
    family <- FAMILIES[[method]]
    fit <- glm(inc ~ factor(origin) + factor(dev), family = family$family, data = d,
               control = glm.control(epsilon = 1e-14, maxit = 100))
    # glm's test is on the deviance alone, and on the gamma's and Tweedie's
    # non-canonical log link IRLS converges linearly, so it stops with the
    # coefficients about 1e-8 short. Refit from them until they settle.
    for (i in 1:20) {
      start <- coef(fit)
      fit <- glm(inc ~ factor(origin) + factor(dev), family = family$family, data = d,
                 start = start, control = glm.control(epsilon = 1e-14, maxit = 100))
      if (max(abs(coef(fit) - start) / pmax(abs(start), 1)) < 1e-13) break
    }
    s <- summary(fit)
    src <- sprintf("R %s glm(inc ~ factor(origin) + factor(dev), family = %s)",
                   getRversion(), family$label)

    co <- s$coefficients
    for (i in seq_len(nrow(co))) {
      emit(name, method, "coefficient", rename(rownames(co)[i]), co[i, "Estimate"], src)
      emit(name, method, "std_error", rename(rownames(co)[i]), co[i, "Std. Error"], src)
    }
    emit(name, method, "dispersion", "", s$dispersion, paste0(src, " summary()$dispersion"))

    # Future cells: below the latest diagonal of a square triangle.
    grid <- expand.grid(origin = origins, dev = devs)
    observed <- paste(d$origin, d$dev)
    future <- grid[!(paste(grid$origin, grid$dev) %in% observed), ]
    future$mean <- predict(fit, newdata = future, type = "response")
    for (o in origins) {
      emit(name, method, "reserve", o, sum(future$mean[future$origin == o]),
           paste0(src, " predict(type = 'response') summed by origin"))
    }
    emit(name, method, "total_reserve", "", sum(future$mean),
         paste0(src, " predict(type = 'response') summed"))
  }
}

header <- c(
  sprintf("# Generated by validation/scripts/reserving_glm_r.R with R %s (stats::glm, statmod %s).",
          getRversion(), utils::packageVersion("statmod")),
  "# Triangles from validation/data/{genins,abc}.csv; RAA is left out (negative increment).",
  "dataset,method,quantity,arg,expected,abs_tol,rel_tol,source"
)
writeLines(c(header, rows), OUT)
cat(sprintf("wrote %d cases to %s\n", length(rows), OUT))
