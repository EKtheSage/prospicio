"""Regenerate validation/reference/reserving_munich_python.csv.

The Munich chain ladder against chainladder-python's MunichAdjustment on
its "mcl" sample (Quarg and Mack's example, validation/data/mcl.csv). Run
from the repository root:

    uv run --no-project --with chainladder==0.10.1 python validation/scripts/reserving_munich_python.py

Each arm fits `Development(sigma_interpolation=...)`, then
`MunichAdjustment(paid_to_incurred=("paid", "incurred"))`, and reads the
ultimates of `Chainladder()` on the adjusted factors. Under "mack" the
oldest age's rho is left out: chainladder-python fills it with Mack's rule
and R ChainLadder (which prospicio follows) log-linearly; neither uses it
without a tail. `arg` is the origin year for per-origin quantities, the age
in months for per-age ones, and empty for the lambdas.
"""

import warnings

import chainladder as cl

OUT = "validation/reference/reserving_munich_python.csv"
VER = cl.__version__
REL = 1e-12
ABS = 1e-9

warnings.filterwarnings("ignore")
rows = []


def emit(test, quantity, arg, value, source):
    rows.append(f"mcl,{test},{quantity},{arg},{float(value)!r},{ABS},{REL},{source}")


mcl = cl.load_sample("mcl")
years = [int(o.year) for o in mcl.origin]
ages = [int(a) for a in mcl.development]
cols = list(mcl.columns)
for interp in ["log-linear", "mack"]:
    dev = cl.Development(sigma_interpolation=interp).fit_transform(mcl)
    m = cl.MunichAdjustment(paid_to_incurred=("paid", "incurred")).fit(dev)
    src = (
        f"chainladder-python {VER}: MunichAdjustment(('paid', 'incurred')) on "
        f"Development(sigma_interpolation='{interp}')"
    )
    lam = m.lambda_coef_.ravel()
    emit(interp, "lambda_paid", "", lam[0], src + " lambda_coef_[0]")
    emit(interp, "lambda_incurred", "", lam[1], src + " lambda_coef_[1]")
    ult = cl.Chainladder().fit(m.transform(dev)).ultimate_.values[0, :, :, 0]
    for o, y in enumerate(years):
        emit(interp, "ultimate_paid", y, ult[cols.index("paid"), o], src + " then Chainladder().ultimate_")
        emit(interp, "ultimate_incurred", y, ult[cols.index("incurred"), o], src + " then Chainladder().ultimate_")
    # q_f_ and rho_sigma_: [0] is the incurred-on-paid regression (I/P),
    # [1] the paid-on-incurred one (P/I).
    q_f = m.q_f_.reshape(2, -1)
    rho = m.rho_sigma_.reshape(2, -1)
    for s, age in enumerate(ages):
        emit(interp, "q_inverse", age, q_f[0, s], src + " q_f_[0]")
        emit(interp, "q", age, q_f[1, s], src + " q_f_[1]")
        if interp == "mack" and s == len(ages) - 1:
            continue
        emit(interp, "rho_paid", age, rho[0, s], src + " rho_sigma_[0]")
        emit(interp, "rho_incurred", age, rho[1, s], src + " rho_sigma_[1]")
    sigma = dev.sigma_.values[0, :, 0, :]
    for s, age in enumerate(ages[:-1]):
        emit(interp, "sigma_paid", age, sigma[cols.index("paid"), s], src + " sigma_")
        emit(interp, "sigma_incurred", age, sigma[cols.index("incurred"), s], src + " sigma_")

header = [
    f"# Generated by validation/scripts/reserving_munich_python.py with chainladder-python {VER}.",
    "# The Munich chain ladder on the mcl sample.",
    "dataset,test,quantity,arg,expected,abs_tol,rel_tol,source",
]
with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(header + rows) + "\n")
