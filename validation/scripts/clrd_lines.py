"""Regenerate validation/data/clrd_lines.csv.

Uses chainladder-python. Run from the repository root:

    uv run --no-project --with chainladder==0.10.1 python validation/scripts/clrd_lines.py

Every line of the CAS loss reserve database summed over companies
(`load_sample('clrd').groupby('LOB').sum()`): `CumPaidLoss` as `paid` and
`EarnedPremNet` as `premium` (constant across ages for an origin), the
observed upper triangles. The script checks that the `paid` column it writes
is the one already committed (the file had no `premium` before 2026-10-13),
and that wkcomp's rows are `clrd_wkcomp.csv`'s.
"""

import csv
import pathlib

import chainladder as cl

DATA = pathlib.Path(__file__).resolve().parents[1] / "data"
LINES = ["comauto", "medmal", "othliab", "ppauto", "prodliab", "wkcomp"]


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(line for line in f if not line.startswith("#")))


def main():
    tri = cl.load_sample("clrd").groupby("LOB").sum()
    paid = tri["CumPaidLoss"].to_frame(keepdims=True).reset_index()
    prem = tri["EarnedPremNet"].to_frame(keepdims=True).reset_index()
    premium = {
        (r.LOB, r.origin.year, int(r.development)): float(r.EarnedPremNet)
        for r in prem.itertuples()
    }
    rows = []
    for line in LINES:
        part = paid[paid.LOB == line].sort_values(["origin", "development"])
        for r in part.itertuples():
            key = (line, r.origin.year, int(r.development))
            rows.append((line, key[1], key[2], float(r.CumPaidLoss), premium[key]))

    path = DATA / "clrd_lines.csv"
    old = read(path)
    assert len(old) == len(rows), (len(old), len(rows))
    for o, (line, origin, dev, p, _) in zip(old, rows):
        assert (o["lob"], int(o["origin"]), int(o["development"])) == (line, origin, dev)
        assert float(o["paid"]) == p, (o, p)
    wk = read(DATA / "clrd_wkcomp.csv")
    wk_rows = [r for r in rows if r[0] == "wkcomp"]
    assert len(wk) == len(wk_rows)
    for o, r in zip(wk, wk_rows):
        assert (float(o["paid"]), float(o["premium"])) == (r[3], r[4]), (o, r)

    with open(path, "w", newline="") as f:
        f.write(
            "# CAS loss reserve database, every line summed over companies: chainladder-python 0.10.1\n"
            "# load_sample('clrd').groupby('LOB').sum(), CumPaidLoss as paid and EarnedPremNet as premium;\n"
            "# the observed upper triangles. Generated by validation/scripts/clrd_lines.py.\n"
        )
        f.write("lob,origin,development,paid,premium\n")
        for line, origin, dev, p, e in rows:
            f.write(f"{line},{origin},{dev},{p:.0f},{e:.0f}\n")
    print(f"wrote {len(rows)} rows")


if __name__ == "__main__":
    main()
