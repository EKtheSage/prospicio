# Regenerate validation/reference/reserving_munich_r.csv from R
# ChainLadder's MunichChainLadder (Quarg and Mack 2004) on its MCLpaid and
# MCLincurred, the triangles of validation/data/mcl.csv.
#
# Run from the repository root:
#
#     Rscript validation/scripts/reserving_munich_r.R
#
# Every arm sets est.sigmaP = est.sigmaI = "Mack". R's default,
# "log-linear", falls back to Mack's rule on this data with a warning (its
# log-linear model of sigma has a p-value above 5%), which prospicio's Mack
# does not do; the default call's numbers are those of the Mack arm.
# `test` is `mack` followed by the tails: none, R's log-linear tail
# (tailP = tailI = TRUE), or the constants 1.05 for paid and 1.02 for
# incurred. `arg` is the origin year (2001 for R's origin 1) for
# per-origin quantities, the age in months for per-age ones, and empty for
# the lambdas.

suppressPackageStartupMessages(library(ChainLadder))

OUT <- "validation/reference/reserving_munich_r.csv"
VER <- as.character(packageVersion("ChainLadder"))
REL <- 1e-12
ABS <- 1e-9

rows <- character(0)
emit <- function(test, quantity, arg, value, source) {
  rows <<- c(rows, sprintf("mcl,%s,%s,%s,%s,%s,%s,%s", test, quantity, arg,
                           sprintf("%.17g", value), format(ABS), format(REL), source))
}

arms <- list(
  list(test = "mack", tailP = FALSE, tailI = FALSE, label = "FALSE, FALSE"),
  list(test = "mack;tail=log-linear", tailP = TRUE, tailI = TRUE, label = "TRUE, TRUE"),
  list(test = "mack;tail=1.05/1.02", tailP = 1.05, tailI = 1.02, label = "1.05, 1.02")
)
n <- ncol(MCLpaid)
ages <- 12 * seq_len(n)
years <- 2000 + seq_len(nrow(MCLpaid))
for (a in arms) {
  m <- suppressWarnings(MunichChainLadder(MCLpaid, MCLincurred, est.sigmaP = "Mack",
                                          est.sigmaI = "Mack", tailP = a$tailP, tailI = a$tailI))
  src <- sprintf("R ChainLadder %s: MunichChainLadder(MCLpaid, MCLincurred, est.sigmaP = 'Mack', est.sigmaI = 'Mack', tailP/tailI = %s)", VER, a$label)
  emit(a$test, "lambda_paid", "", coef(m$lambdaP)[1], paste0(src, "$lambdaP"))
  emit(a$test, "lambda_incurred", "", coef(m$lambdaI)[1], paste0(src, "$lambdaI"))
  ult <- ncol(m$MCLPaid)
  for (o in seq_along(years)) {
    emit(a$test, "ultimate_paid", years[o], m$MCLPaid[o, ult], paste0(src, "$MCLPaid"))
    emit(a$test, "ultimate_incurred", years[o], m$MCLIncurred[o, ult], paste0(src, "$MCLIncurred"))
  }
  for (s in seq_len(n)) {
    emit(a$test, "q", ages[s], m$q.f[s], paste0(src, "$q.f"))
    emit(a$test, "q_inverse", ages[s], m$qinverse.f[s], paste0(src, "$qinverse.f"))
    emit(a$test, "rho_paid", ages[s], m$rhoP.sigma[s], paste0(src, "$rhoP.sigma"))
    emit(a$test, "rho_incurred", ages[s], m$rhoI.sigma[s], paste0(src, "$rhoI.sigma"))
  }
  for (s in seq_len(n - 1)) {
    emit(a$test, "sigma_paid", ages[s], m$MackPaid$sigma[s], paste0(src, "$MackPaid$sigma"))
    emit(a$test, "sigma_incurred", ages[s], m$MackIncurred$sigma[s], paste0(src, "$MackIncurred$sigma"))
  }
  if (!isFALSE(a$tailP)) {
    emit(a$test, "tail_paid", "", m$MackPaid$f[n], paste0(src, "$MackPaid$f[n]"))
    emit(a$test, "tail_sigma_paid", "", m$MackPaid$sigma[n], paste0(src, "$MackPaid$sigma[n]"))
    emit(a$test, "tail_incurred", "", m$MackIncurred$f[n], paste0(src, "$MackIncurred$f[n]"))
    emit(a$test, "tail_sigma_incurred", "", m$MackIncurred$sigma[n], paste0(src, "$MackIncurred$sigma[n]"))
  }
}

header <- c(
  sprintf("# Generated by validation/scripts/reserving_munich_r.R with %s, ChainLadder %s.",
          R.version.string, VER),
  "# The Munich chain ladder on MCLpaid and MCLincurred.",
  "dataset,test,quantity,arg,expected,abs_tol,rel_tol,source")
writeLines(c(header, rows), OUT)
