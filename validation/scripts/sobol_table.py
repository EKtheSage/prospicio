"""Write crates/prospicio-math/src/sobol_table.rs from SciPy's Sobol direction numbers.

Joe and Kuo's new-joe-kuo-6.21201 table as SciPy ships it
(scipy/stats/_sobol_direction_numbers.npz), the first 1,111 dimensions.
Run with SciPy 1.14.1: python3 validation/scripts/sobol_table.py
"""

import os
from pathlib import Path

import numpy as np
import scipy

D = 1111
OUT = Path(__file__).resolve().parents[2] / "crates/prospicio-math/src/sobol_table.rs"


def rows(values, width):
    return ["    " + ", ".join(map(str, values[i:i + width])) + "," for i in range(0, len(values), width)]


def main():
    z = np.load(os.path.join(os.path.dirname(scipy.__file__), "stats", "_sobol_direction_numbers.npz"))
    poly = [int(x) for x in z["poly"][:D]]
    vinit = z["vinit"]
    starts, flat = [0], []
    for d in range(D):
        s = poly[d].bit_length() - 1 if d > 0 else 0
        flat += [int(x) for x in vinit[d, :s]]
        starts.append(len(flat))
    out = [
        "//! Joe and Kuo's Sobol direction numbers (`new-joe-kuo-6.21201`), the first",
        f"//! {D:,} dimensions, as SciPy {scipy.__version__} ships them in",
        "//! `scipy/stats/_sobol_direction_numbers.npz`. Generated by",
        "//! `validation/scripts/sobol_table.py`; do not edit.",
        "",
        "/// Dimensions carried.",
        f"pub(crate) const MAX_DIM: usize = {D};",
        "",
        "/// Each dimension's primitive polynomial, its leading and trailing bits",
        "/// included (dimension 0, the van der Corput sequence, has none and is 1).",
        f"pub(crate) static POLY: [u32; {D}] = [",
        *rows(poly, 12),
        "];",
        "",
        "/// The odd initial values `m_1, ..., m_s` of each dimension, concatenated;",
        "/// dimension `d` holds `INIT[INIT_START[d]..INIT_START[d + 1]]`.",
        f"pub(crate) static INIT_START: [u32; {D + 1}] = [",
        *rows(starts, 12),
        "];",
        "",
        f"pub(crate) static INIT: [u32; {len(flat)}] = [",
        *rows(flat, 14),
        "];",
    ]
    OUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
