# Regenerate validation/reference/reserving_assumptions_r.csv from R
# ChainLadder's cyEffTest and dfCorTest (Mack 1994, appendices H and G).
#
# Run from the repository root:
#
#     Rscript validation/scripts/reserving_assumptions_r.R
#
# Triangles are read from validation/data/{raa,genins,abc}.csv. Each test
# runs at its default level (cyEffTest 0.95, dfCorTest 0.5) and at a second
# one (0.9 and 0.75). `test` is `calendar_year_effect` or
# `development_correlation` followed by `ci=`. `arg` is the calendar year of
# a diagonal's later cells (R's row j is first origin + j) for per-diagonal
# quantities, the 0-based position of the first link of a pair (R's i - 1)
# for per-pair ones, and empty for totals.

suppressPackageStartupMessages(library(ChainLadder))

OUT <- "validation/reference/reserving_assumptions_r.csv"
DATASETS <- c("raa", "genins", "abc")
VER <- as.character(packageVersion("ChainLadder"))
REL <- 1e-12
ABS <- 1e-12

read_triangle <- function(name) {
  d <- read.csv(file.path("validation/data", paste0(name, ".csv")), comment.char = "#")
  origins <- sort(unique(d$origin))
  devs <- sort(unique(d$development))
  tri <- matrix(NA_real_, length(origins), length(devs),
                dimnames = list(origin = origins, dev = devs))
  tri[cbind(match(d$origin, origins), match(d$development, devs))] <- d$value
  as.triangle(tri)
}

rows <- character(0)
emit <- function(dataset, test, quantity, arg, value, source) {
  rows <<- c(rows, sprintf("%s,%s,%s,%s,%s,%s,%s,%s", dataset, test, quantity, arg,
                           sprintf("%.17g", value), format(ABS), format(REL), source))
}

for (name in DATASETS) {
  tri <- read_triangle(name)
  first <- as.integer(rownames(tri)[1])
  for (ci in c(0.95, 0.9)) {
    cy <- cyEffTest(tri, ci = ci)
    test <- sprintf("calendar_year_effect;ci=%s", ci)
    src <- sprintf("R ChainLadder %s: cyEffTest(tri, ci = %s)", VER, ci)
    tab <- cy$test_table
    for (r in seq_len(nrow(tab))) {
      year <- first + tab$j[r]
      emit(name, test, "small", year, tab$S_j[r], paste0(src, "$test_table$S_j"))
      emit(name, test, "large", year, tab$L_j[r], paste0(src, "$test_table$L_j"))
      emit(name, test, "z", year, tab$Z_j[r], paste0(src, "$test_table$Z_j"))
      emit(name, test, "n", year, tab$n[r], paste0(src, "$test_table$n"))
      emit(name, test, "m", year, tab$m[r], paste0(src, "$test_table$m"))
      emit(name, test, "expected", year, tab$E_Zj[r], paste0(src, "$test_table$E_Zj"))
      emit(name, test, "variance", year, tab$Var_Zj[r], paste0(src, "$test_table$Var_Zj"))
    }
    emit(name, test, "n_diagonals", "", nrow(tab), paste0(src, " nrow(test_table)"))
    emit(name, test, "total_z", "", cy$Z, paste0(src, "$Z"))
    emit(name, test, "total_expected", "", cy$E, paste0(src, "$E"))
    emit(name, test, "total_variance", "", cy$Var, paste0(src, "$Var"))
    emit(name, test, "lower", "", cy$Range[1], paste0(src, "$Range[1]"))
    emit(name, test, "upper", "", cy$Range[2], paste0(src, "$Range[2]"))
    emit(name, test, "passes", "", as.numeric(cy$Z >= cy$Range[1] & cy$Z <= cy$Range[2]),
         paste0(src, " !(Calendar Year Effect)"))
  }
  for (ci in c(0.5, 0.75)) {
    dc <- dfCorTest(tri, ci = ci)
    test <- sprintf("development_correlation;ci=%s", ci)
    src <- sprintf("R ChainLadder %s: dfCorTest(tri, ci = %s)", VER, ci)
    # dfCorTest returns T alone; its T_k are cor(ata[, i], ata[, i + 1],
    # method = "spearman", use = "pairwise.complete.obs"), as in its code.
    n <- dim(tri)[1]
    ata_tri <- ata(tri)[1:n - 1, ]
    for (i in 1:(n - 3)) {
      tk <- cor(ata_tri[, i], ata_tri[, i + 1], method = "spearman", use = "pairwise.complete.obs")
      emit(name, test, "t_k", i - 1, tk, sprintf("R ChainLadder %s: dfCorTest's T_k", VER))
      emit(name, test, "weight", i - 1, n - 2 - i, sprintf("R ChainLadder %s: dfCorTest's weights (n - 3):1", VER))
    }
    emit(name, test, "n_pairs", "", n - 3, paste0(src, " length(T_k)"))
    emit(name, test, "t", "", dc$T_stat, paste0(src, "$T_stat"))
    emit(name, test, "variance", "", dc$Var, paste0(src, "$Var"))
    emit(name, test, "lower", "", dc$Range[1], paste0(src, "$Range[1]"))
    emit(name, test, "upper", "", dc$Range[2], paste0(src, "$Range[2]"))
    emit(name, test, "passes", "", as.numeric(dc$T_stat >= dc$Range[1] & dc$T_stat <= dc$Range[2]),
         paste0(src, " !(Development Factor Correlation)"))
  }
}

header <- c(
  sprintf("# Generated by validation/scripts/reserving_assumptions_r.R with %s, ChainLadder %s.",
          R.version.string, VER),
  "# Mack's calendar-year effect and development-factor correlation tests on every observed link ratio.",
  "dataset,test,quantity,arg,expected,abs_tol,rel_tol,source")
writeLines(c(header, rows), OUT)
