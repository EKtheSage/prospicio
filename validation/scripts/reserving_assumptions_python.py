"""Regenerate validation/reference/reserving_assumptions_python.csv.

Mack's calendar-year effect and development-factor correlation tests
against chainladder-python's ValuationCorrelation and
DevelopmentCorrelation. Run from the repository root:

    uv run --no-project --with chainladder==0.10.1 python validation/scripts/reserving_assumptions_python.py

Only the statistics chainladder-python computes as R ChainLadder does are
kept (knowledge/references/chainladder-python-correlation.md; the departures
are in chainladder-python-correlation-traps.md):

* ValuationCorrelation(total=True): z, z_expectation and z_variance. Its
  range and z_critical are not targets: the range is centred on the sum of
  the variances instead of E[Z], and z_critical compares that sum with it,
  so it is False on every triangle.
* ValuationCorrelation(total=False): each diagonal's z, E[Z_j] and Var[Z_j]
  (its z_critical is Mack 1997's per-diagonal binomial test, another test).
  Its first diagonal, of one link ratio, is not in R's table and is left
  out.
* DevelopmentCorrelation(p_critical=0.5): each T_k, its weight, T, its
  variance and the 50% interval (p_critical is 1 - ci).

`arg` is the calendar year of a diagonal's later cells, or the 0-based
position of the first link of a pair, and empty for totals.
"""

import warnings

import chainladder as cl

OUT = "validation/reference/reserving_assumptions_python.csv"
VER = cl.__version__
REL = 1e-12
ABS = 1e-12
DATASETS = ["raa", "genins", "abc"]

warnings.filterwarnings("ignore")
rows = []


def emit(dataset, test, quantity, arg, value, source):
    rows.append(f"{dataset},{test},{quantity},{arg},{float(value)!r},{ABS},{REL},{source}")


for name in DATASETS:
    tri = cl.load_sample(name)
    first = int(tri.origin[0].year)
    test = "calendar_year_effect"
    total = cl.ValuationCorrelation(tri, p_critical=0.05, total=True)
    src = f"chainladder-python {VER}: ValuationCorrelation(tri, total=True)"
    emit(name, test, "total_z", "", total.z.iloc[0, 0], src + ".z")
    emit(name, test, "total_expected", "", total.z_expectation.iloc[0, 0], src + ".z_expectation")
    emit(name, test, "total_variance", "", total.z_variance.iloc[0, 0], src + ".z_variance")
    per = cl.ValuationCorrelation(tri, p_critical=0.05, total=False)
    src = f"chainladder-python {VER}: ValuationCorrelation(tri, total=False)"
    z = per.z.values.ravel()
    ez = per.z_expectation.values.ravel()
    vz = per.z_variance.values.ravel()
    # Position p is the diagonal ending at first + p + 1; the first (one
    # link ratio) is not in R's table.
    for p in range(1, len(z)):
        year = first + p + 1
        emit(name, test, "z", year, z[p], src + ".z")
        emit(name, test, "expected", year, ez[p], src + ".z_expectation")
        emit(name, test, "variance", year, vz[p], src + ".z_variance")

    test = "development_correlation"
    dc = cl.DevelopmentCorrelation(tri, p_critical=0.5)
    src = f"chainladder-python {VER}: DevelopmentCorrelation(tri, p_critical=0.5)"
    t = dc.t.values.ravel()
    w = dc.weights.values.ravel()
    for i in range(len(t)):
        emit(name, test, "t_k", i, t[i], src + ".t")
        emit(name, test, "weight", i, w[i], src + ".weights")
    emit(name, test, "t", "", dc.t_expectation.iloc[0, 0], src + ".t_expectation")
    emit(name, test, "variance", "", dc.t_variance, src + ".t_variance")
    emit(name, test, "lower", "", dc.confidence_interval[0], src + ".confidence_interval[0]")
    emit(name, test, "upper", "", dc.confidence_interval[1], src + ".confidence_interval[1]")

with open(OUT, "w", newline="\n") as f:
    f.write(f"# Generated by validation/scripts/reserving_assumptions_python.py with chainladder {VER}.\n")
    f.write("# The statistics of ValuationCorrelation and DevelopmentCorrelation that match R ChainLadder's.\n")
    f.write("dataset,test,quantity,arg,expected,abs_tol,rel_tol,source\n")
    f.write("\n".join(rows) + "\n")
