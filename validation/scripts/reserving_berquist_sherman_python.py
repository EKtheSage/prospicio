"""Regenerate validation/reference/reserving_berquist_sherman_python.csv and the
data files validation/data/berqsherm_{auto,medmal}.csv.

Uses chainladder-python. Run from the repository root:

    uv run --no-project --with chainladder==0.10.1 python validation/scripts/reserving_berquist_sherman_python.py

The data is chainladder-python's `berqsherm` sample: Berquist and Sherman's
(1977) automobile bodily injury and medical malpractice examples, which
Friedland reprints in chapter 13 (Exhibits I and II), with columns Incurred,
Paid, Reported and Closed. `BerquistSherman` adjusts incurred for case reserve
adequacy (open counts are reported less closed, the trend detrends the latest
diagonal's average case outstanding) and paid and closed counts for the
settlement rate (disposal rates of the latest diagonal over the chain ladder's
ultimate reported counts, two-point exponential fits of paid on closed). Each
case is one adjusted cell: `quantity` is the column, `arg` is `origin:age`.
`method` names the trend. The chain ladder ultimates on the adjusted columns
(volume-weighted, all years) are cases too.
"""

import csv
import warnings

import chainladder as cl
import numpy as np

OUT = "validation/reference/reserving_berquist_sherman_python.csv"
VER = cl.__version__
REL = 1e-9
TRENDS = [0.15, 0.05]
LOBS = {"Auto": "berqsherm_auto", "MedMal": "berqsherm_medmal"}
COLUMNS = {"Incurred": "incurred", "Paid": "paid", "Reported": "reported", "Closed": "closed"}


def fmt(x):
    return repr(float(x))


def cells(tri):
    """(origin year, age in months, value) of every observed cell."""
    values = tri.values[0, 0]
    origins = [d.year for d in tri.origin.to_timestamp()]
    ages = list(tri.development)
    for i, o in enumerate(origins):
        for j, a in enumerate(ages):
            v = values[i, j]
            if not np.isnan(v):
                yield o, int(a), v


def write_data(tri, lob, name):
    t = tri.loc[lob]
    table = {}
    for col, short in COLUMNS.items():
        for o, a, v in cells(t[col]):
            table.setdefault((o, a), {})[short] = v
    with open(f"validation/data/{name}.csv", "w", newline="") as f:
        f.write(f"# chainladder-python {VER} sample berqsherm, LOB {lob}: Berquist and Sherman (1977), as\n")
        f.write("# reprinted in Friedland (2010), chapter 13. Cumulative incurred and paid claims, reported and closed counts.\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["origin", "development", *COLUMNS.values()])
        for (o, a), row in sorted(table.items()):
            w.writerow([o, a, *[fmt(row[c]) for c in COLUMNS.values()]])


def main():
    tri = cl.load_sample("berqsherm")
    rows = []
    for lob, name in LOBS.items():
        write_data(tri, lob, name)
        t = tri.loc[lob]
        for trend in TRENDS:
            method = f"berquist_sherman;trend={trend}"
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                m = cl.BerquistSherman(
                    paid_amount="Paid",
                    incurred_amount="Incurred",
                    reported_count="Reported",
                    closed_count="Closed",
                    trend=trend,
                ).fit(t)
            adj = m.adjusted_triangle_
            src = (
                f"chainladder-python {VER}: BerquistSherman(paid_amount='Paid', incurred_amount='Incurred', "
                f"reported_count='Reported', closed_count='Closed', trend={trend}).fit(berqsherm.loc['{lob}'])"
            )
            for col in ["Incurred", "Paid", "Closed"]:
                for o, a, v in cells(adj[col]):
                    rows.append([name, method, COLUMNS[col], f"{o}:{a}", fmt(v), 0, REL,
                                 f"{src}.adjusted_triangle_['{col}']"])
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore")
                    ult = cl.Chainladder().fit(adj[col]).ultimate_
                for o, _, v in cells(ult):
                    rows.append([name, method, f"{COLUMNS[col]}_ultimate", str(o), fmt(v), 0, REL,
                                 f"{src}; Chainladder().fit(adjusted_triangle_['{col}']).ultimate_"])
    with open(OUT, "w", newline="") as f:
        f.write(f"# Generated by validation/scripts/reserving_berquist_sherman_python.py with chainladder-python {VER}.\n")
        f.write("# Data: validation/data/berqsherm_{auto,medmal}.csv (chainladder-python's berqsherm sample).\n")
        f.write("# arg is origin:age for an adjusted cell and the origin for a chain ladder ultimate on an adjusted column.\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["dataset", "method", "quantity", "arg", "expected", "abs_tol", "rel_tol", "source"])
        w.writerows(rows)
    print(f"wrote {len(rows)} cases to {OUT}")


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
